        <h1 id="introduction">Introduction</h1>
<p>REST API aplikacji MealCore: dziennik posiłków z liczeniem kalorii, baza produktów, grupy ze wspólną listą zakupów i panel administratora.</p>
<aside>
    <strong>Base URL</strong>: <code>http://localhost:8080</code>
</aside>
<pre><code>Wszystkie odpowiedzi są w formacie JSON. Błędy mają postać `{"message": "..."}`, a błędy walidacji (422) dodatkowo pole `errors`.

&lt;aside&gt;Konta demo (po `php artisan migrate:fresh --seed`): `admin@mealcore.com` (admin) oraz `alex@mealcore.com` (user), hasło `password`.&lt;/aside&gt;</code></pre>

        <h1 id="authenticating-requests">Authenticating requests</h1>
<p>To authenticate requests, include an <strong><code>Authorization</code></strong> header with the value <strong><code>"Bearer {TOKEN}"</code></strong>.</p>
<p>All authenticated endpoints are marked with a <code>requires authentication</code> badge in the documentation below.</p>
<p>Token otrzymasz z <code>POST /api/auth/login</code> lub <code>POST /api/auth/register</code>. Wysyłaj go w nagłówku <code>Authorization: Bearer {TOKEN}</code>.</p>

